// Generates firestore.rules from shared/modules.js so UI permissions and security rules cannot drift apart.
import { writeFileSync } from 'node:fs';
import { MODULES, PROVIDER_ROLES, hasField, doctorReadMode } from '../shared/modules.js';

const OPS = { r: 'read', c: 'create', u: 'update', d: 'delete' };
const q = (v) => (typeof v === 'string' ? `'${v}'` : String(v));

// Fields restricted via `roles` (e.g. ticket/leave status) cannot be set or changed by other roles.
function guards(m, role, op) {
  let g = '';
  for (const f of (m.fields || []).filter((x) => x.roles && !x.roles.includes(role))) {
    if (op === 'create' && f.default !== undefined) g += ` && request.resource.data.get('${f.name}', ${q(f.default)}) == ${q(f.default)}`;
    if (op === 'update') g += ` && request.resource.data.get('${f.name}', null) == resource.data.get('${f.name}', null)`;
  }
  return g;
}

function block(m) {
  const hasP = hasField(m, 'patientId');
  const hasD = hasField(m, 'doctorId');
  const mode = doctorReadMode(m);
  const cond = { read: [], create: [], update: [], delete: [] };

  for (const ch of m.access.admin || '') cond[OPS[ch]].push('isAdmin()');

  for (const role of PROVIDER_ROLES) for (const ch of m.access[role] || '') {
    let c = `hasRole('${role}')`;
    if (ch === 'r' && mode === 'own') c += ' && resource.data.doctorId == request.auth.uid';
    if (ch === 'c' && hasD) c += ' && request.resource.data.doctorId == request.auth.uid';
    if (ch === 'c' && m.doctorCreate) c += ` && ${m.doctorCreate}`;
    if (ch === 'c' || ch === 'u') c += guards(m, role, ch === 'c' ? 'create' : 'update');
    if (ch === 'u' && hasD) c += ' && resource.data.doctorId == request.auth.uid && request.resource.data.doctorId == request.auth.uid';
    if (ch === 'd' && hasD) c += ' && resource.data.doctorId == request.auth.uid';
    cond[OPS[ch]].push(c);
    if (ch === 'r' && role === 'doctor' && hasP && mode === 'own') cond.read.push("hasRole('doctor') && isMyPatient(resource.data.patientId)");
  }

  for (const ch of m.access.patient || '') {
    let c = 'isPatient()';
    if (ch === 'r' && hasP) c += ' && resource.data.patientId == request.auth.uid';
    if (ch === 'c') {
      if (hasP) c += ' && request.resource.data.patientId == request.auth.uid';
      if (m.patientCreate) c += ` && ${m.patientCreate}`;
      c += guards(m, 'patient', 'create');
    }
    if (ch === 'u') {
      if (hasP) c += ' && resource.data.patientId == request.auth.uid && request.resource.data.patientId == request.auth.uid';
      if (m.patientUpdate) c += ` && ${m.patientUpdate}`;
      c += guards(m, 'patient', 'update');
    }
    if (ch === 'd' && hasP) c += ' && resource.data.patientId == request.auth.uid';
    cond[OPS[ch]].push(c);
  }

  const lines = Object.entries(cond)
    .filter(([, v]) => v.length)
    .map(([op, v]) => `      allow ${op}: if ${v.join('\n        || ')};`);
  if (m.extraRules) lines.push(`      ${m.extraRules}`);
  return `    match /${m.key}/{id} {\n${lines.join('\n')}\n    }`;
}

const generated = MODULES.filter((m) => !m.custom && !m.source).map(block).join('\n\n');

const rules = `// GENERATED by scripts/gen-rules.mjs from shared/modules.js - do not edit by hand.
rules_version = '2';
service cloud.firestore {
  match /databases/{database}/documents {

    function signedIn() { return request.auth != null; }
    function me() { return get(/databases/$(database)/documents/users/$(request.auth.uid)).data; }
    function hasRole(r) { return signedIn() && me().role == r && me().get('active', true) == true; }
    function isAdmin() { return hasRole('admin'); }
    function isProvider() { return signedIn() && me().role in ['doctor', 'nutritionist', 'yogaTeacher', 'naturopath'] && me().get('active', true) == true; }
    function isDoctor() { return isProvider(); }
    function isPatient() { return hasRole('patient'); }
    function isMyPatient(pid) { return get(/databases/$(database)/documents/users/$(pid)).data.primaryProviderId == request.auth.uid; }

    // ---- users: self-registration is patient-only; roles are changed by admins only
    match /users/{uid} {
      allow read: if signedIn() && (
        request.auth.uid == uid
        || resource.data.role in ['doctor', 'nutritionist', 'yogaTeacher', 'naturopath']
        || (isProvider() && resource.data.role == 'patient' && resource.data.primaryProviderId == request.auth.uid)
        || isAdmin());
      allow create: if signedIn() && (
        (request.auth.uid == uid && request.resource.data.role == 'patient' && request.resource.data.active == true)
        || isAdmin());
      allow update: if signedIn() && (
        (request.auth.uid == uid && !request.resource.data.diff(resource.data).affectedKeys().hasAny(['role', 'active', 'primaryProviderId']))
        || isAdmin());
      allow delete: if isAdmin();
    }

${generated}
  }
}
`;

writeFileSync(new URL('../firestore.rules', import.meta.url), rules);
console.log(`firestore.rules written for ${MODULES.filter((m) => !m.custom && !m.source).length} collections`);
